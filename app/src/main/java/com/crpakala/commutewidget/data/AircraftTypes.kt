/** Readable name for an ICAO type designator, or null when the code is blank or unknown. */
internal fun aircraftTypeName(icao: String?): String? {
    val code = icao?.trim()?.takeIf { it.isNotEmpty() } ?: return null
    return AIRCRAFT_TYPE_NAMES[code.uppercase()]
}

/** The whole table, so its size and contents can be asserted on. */
internal fun aircraftTypeNames(): Map<String, String> = AIRCRAFT_TYPE_NAMES
